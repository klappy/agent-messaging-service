#!/usr/bin/env node
// Bundles canon/constraints/portal-bootstrap-content.md into the Worker so the
// portal bootstrap has NO runtime dependency on oddkit (oddkit legacy-caller
// audit, 2026-09-26). Pattern borrowed from ptxprint-mcp's own bundled docs:
// klappy/kitchen rail/6-learned/2026-09-05-ptxprint-docs-v2-progressive-disclosure.
// Usage: node scripts/bundle-canon.mjs          (regenerate)
//        node scripts/bundle-canon.mjs --check  (exit 1 if bundle drifted from canon)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../../canon/constraints/portal-bootstrap-content.md");
const out = resolve(here, "../src/canon-bundle.generated.ts");
const md = readFileSync(src, "utf8");
const ts =
  "// GENERATED by scripts/bundle-canon.mjs from canon/constraints/portal-bootstrap-content.md.\n" +
  "// Do not edit by hand; rerun the script after canon changes.\n" +
  `export const PORTAL_BOOTSTRAP_CANON: string = ${JSON.stringify(md)};\n`;
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(out, "utf8"); } catch {}
  if (cur !== ts) { console.error("canon bundle drifted: run node packages/tincan/scripts/bundle-canon.mjs"); process.exit(1); }
  console.log("canon bundle in sync");
} else { writeFileSync(out, ts); console.log("wrote", out); }
